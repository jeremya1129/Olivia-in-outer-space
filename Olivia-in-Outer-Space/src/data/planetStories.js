/**
 * Helper to get the story object for a celestial body id.
 * Always returns a valid story object with title, text, and sightWords.
 */
export function getStoryForBody(bodyId, bodyName = '') {
  if (bodyId && PLANET_STORIES[bodyId]) {
    return PLANET_STORIES[bodyId];
  }
  const cleanName = bodyName || bodyId || 'Outer Space';
  return {
    title: `Exploring ${cleanName}!`,
    emoji: "🚀",
    text: `Captain Olivia and Navigator Anna fly high into outer space to visit ${cleanName}! Space exploration is so much fun!`,
    sightWords: ["fly", "high", "space", "fun"],
    actionSound: "twinkle",
  };
}
